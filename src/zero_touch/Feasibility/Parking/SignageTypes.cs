
namespace Parking
{
    /// <summary>
    /// Defines enums for the types of parking signage.
    /// </summary>
    public enum SignageType
    {
        /// <summary>
        /// Electric vehicle parking.
        /// </summary>
        EV,

        /// <summary>
        /// Parking for Persons With Disabilities.
        /// </summary>
        PWD,

        /// <summary>
        /// Generic parking P signage.
        /// </summary>
        Standard,

        /// <summary>
        /// Car parking.
        /// </summary>
        Car,

        /// <summary>
        /// Bicycle parking.
        /// </summary>
        Bicycle,

        /// <summary>
        /// Motorbike parking.
        /// </summary>
        Motorbike,

        /// <summary>
        /// No parking signage.
        /// </summary>
        NoParking,

        /// <summary>
        /// No signage requirement for the parking bay.
        /// </summary>
        NoSignage,
    }
}